import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {captureEpisode} from '../../scripts/capture-browser.mjs';
const {note,noteTitle,importTitle}=JSON.parse(await readFile(new URL('targets.json',import.meta.url)));
await captureEpisode(import.meta.url, {login:true}, async ({page,go,snap,origin})=>{
  await page.setViewportSize({width:840,height:800});
  await go('/notes');
  const start=page.getByRole('link',{name:'Importieren',exact:true});
  await snap(1,[page.getByRole('heading',{name:'Notizen',exact:true}),start],{size:[840,270],point:start});
  await start.click();
  await page.setViewportSize({width:1280,height:800});
  const file=page.locator('input[type=file]');
  const preview=page.getByRole('button',{name:'Importvorschau erstellen'});
  await file.setInputFiles(fileURLToPath(new URL('Gnade-im-Alltag.md',import.meta.url)));
  await preview.click();
  const panel=page.getByTestId('import-preview');
  const title=panel.getByRole('heading',{name:importTitle});
  await snap(2,title,{size:[730,310],offset:[25,45]});
  const confirm=panel.getByRole('button',{name:'Als privates Dokument importieren'});
  await confirm.scrollIntoViewIfNeeded();
  await snap(3,confirm,{size:[550,270],offset:[-120,-65],point:confirm});
  await go(note);
  const menu=page.locator('details.export-menu');
  await menu.locator('summary').click();
  await snap(4,menu.locator('div'),{size:[355,205],point:menu.getByText('Word (.docx)',{exact:true})});
  const response=await page.request.get(new URL(note+'/export.md',origin).href);
  if (!response.ok()) throw new Error('Markdown export failed.');
  await go('/notes/import');
  await file.setInputFiles({name:'Gnade-die-traegt.md',mimeType:'text/markdown',buffer:await response.body()});
  await preview.click();
  await panel.getByRole('heading',{name:noteTitle}).waitFor();
  await snap(5,panel.locator('.metadata-chip').first(),{size:[750,295],offset:[135,2]});
});
