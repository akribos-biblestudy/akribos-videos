const { capture, reader, nav, signIn, field } = require('./session.cjs')
async function orient(p, take, config) {
  await nav(p, reader('Joh3,1', ['ELB1905', 'GERKINGCOMMENTS']))
  await take()
  await field(p).fill('Joh 3,16')
  await field(p).press('Enter')
  await p.locator('[data-verse-key="43:3:16"].highlighted').first().waitFor()
  await take()
  await p.getByRole('button', { name: 'Ressource in Bereich 1 öffnen' }).click()
  const searchInput = p.locator('input[placeholder*="Werk suchen"]').first()
  await searchInput.waitFor()
  await take()
  await signIn(p)
  await nav(p, reader('Joh3,16', ['ELB1905']))
  await p.getByRole('button', { name: 'Konto-Menü' }).click()
  const docs = p.getByRole('menuitem', { name: 'Notizen & Ausarbeitungen' })
  await docs.waitFor()
  await take()
  await docs.click()
  await p.waitForURL((u) => u.pathname.startsWith('/notes'))
  const collections = p.getByRole('link', { name: 'Stellensammlungen', exact: true }).first()
  await collections.waitFor()
  await p.setViewportSize(config.documentViewport)
  const help = p.getByRole('menuitem', { name: 'Hilfe', exact: true })
  if (!(await help.isVisible())) await p.getByRole('button', { name: 'Konto-Menü' }).click()
  await help.waitFor()
  await p.getByRole('menuitem', { name: 'Produkt-Tour', exact: true }).waitFor()
  await take()
}
capture(__dirname, orient).catch((error) => {
  console.error(error.message)
  process.exitCode = 1
})
